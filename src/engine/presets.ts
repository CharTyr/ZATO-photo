export function mergeConfig(base: ZatoConfig, patch: PartialDeep<ZatoConfig>): ZatoConfig {
  return {
    canvas: { ...base.canvas, ...patch.canvas },
    desaturate: { ...base.desaturate, ...patch.desaturate },
    basePalettize: { ...base.basePalettize, ...patch.basePalettize },
    thresholds: { ...base.thresholds, ...patch.thresholds },
    colouring: {
      ...base.colouring,
      ...patch.colouring,
      curvePoints: patch.colouring?.curvePoints
        ? patch.colouring.curvePoints.map((p) => ({ ...p }))
        : base.colouring.curvePoints.map((p) => ({ ...p })),
      colorPalettize: {
        ...base.colouring.colorPalettize,
        ...patch.colouring?.colorPalettize,
      },
      gradientMapStops: patch.colouring?.gradientMapStops
        ? patch.colouring.gradientMapStops.map((s) => ({ ...s }))
        : base.colouring.gradientMapStops.map((s) => ({ ...s })),
      overlayStops: patch.colouring?.overlayStops
        ? patch.colouring.overlayStops.map((s) => ({ ...s }))
        : base.colouring.overlayStops.map((s) => ({ ...s })),
    },
    noise: { ...base.noise, ...patch.noise },
    posterize: { ...base.posterize, ...patch.posterize },
  };
}

